import json

import pytest

from vultr_model_catalog import (
    CatalogError,
    MediaIssue,
    build_media_catalog,
    load_media_catalog,
    normalize_model,
    parse_catalog,
    speech_model_ids,
)

SPEECH = ["auk", "chatterbox", "qwen3-tts-12hz-1.7b"]
BASE = "https://api.vultrinference.com/v1"
PATHS = {
    "/models?format=openrouter&output_modalities=all": "media/public-models.json",
    "/images/models": "media/image-models.json",
    "/videos/models": "media/video-models.json",
    "/music/models": "media/music-models.json",
    **{f"/audio/voices?model={model_id}": f"media/voices-{model_id}.json" for model_id in SPEECH},
}


@pytest.fixture
def payloads(load):
    """The public catalogs as captured, keyed the way fetch_media_payloads keys them."""
    return {
        "public": load("media/public-models.json"),
        "image": load("media/image-models.json"),
        "video": load("media/video-models.json"),
        "music": load("media/music-models.json"),
        "voices": {model_id: load(f"media/voices-{model_id}.json") for model_id in SPEECH},
    }


# The pinned output is generated by the TypeScript project (UPDATE_FIXTURES=1 npm test).
def test_media_catalogs_match_the_pinned_canonical_output(load, payloads):
    models = build_media_catalog(payloads, "network", 0).models
    assert [model.to_dict() for model in models] == load("media.normalized.json")


def test_one_record_per_model_with_each_surfaces_entry(payloads):
    catalog = build_media_catalog(payloads, "network", 0)
    assert catalog.issues == []
    by_id = {model.id: model for model in catalog.models}

    h3 = by_id["minimax-h3"]
    assert h3.image and h3.video
    assert sorted(h3.quality_tiers) == ["image", "video"]
    assert h3.rate_limits["video"]["active_jobs"] == 2
    assert [(mode["mode"], mode["also"]) for mode in h3.image["modes"]] == [("ref", {"steps": [8]}), ("generate", {"steps": [4]})]

    speech = by_id["qwen3-tts-12hz-1.7b"].speech
    assert len(speech.voices) == 11
    assert "Japanese" in speech.languages
    assert by_id["minimax-music3"].music
    assert by_id["glm-5.3"].image is None
    assert by_id["glm-5.3"].rate_limits["text"]


def test_the_speech_models_are_the_public_shapes_entries_with_voices(load):
    assert speech_model_ids(load("media/public-models.json")) == SPEECH


def test_a_malformed_payload_or_entry_is_an_issue_never_a_failure():
    catalog = build_media_catalog(
        {"image": {"data": [{"id": "ok", "supported_parameters": {}}, {"name": "no id"}]}, "video": {"nope": True}, "voices": {"x": []}},
        "network",
        0,
    )
    assert [model.id for model in catalog.models] == ["ok"]
    assert catalog.issues == [
        MediaIssue("image", "entry 1 has no id"),
        MediaIssue("video", "payload has no data list"),
        MediaIssue("voices:x", "payload has no data list"),
    ]


def test_the_provider_documents_modalities_outputs_and_inputs(load):
    models = [normalize_model(document) for document in parse_catalog(load("media/provider-models.json")).documents]
    h3 = next(model for model in models if model.id == "minimax-h3")
    assert [output.type for output in h3.outputs] == ["video", "image"]
    assert h3.output_of("video").pricing[0]["unit"] == "second"
    assert h3.output_of("video").parameters["duration"]["default"] == 6
    assert h3.input_of("image").supported_inputs["references"] == {"type": "integer", "min": 1, "max": 9}
    assert h3.output_of("text") is None
    chat = next(model for model in models if model.id == "glm-5.3")
    assert chat.output_of("text").parameters == chat.parameters


class FakeTransport:
    def __init__(self, load, failing=lambda path: False):
        self.load = load
        self.failing = failing
        self.calls = []

    def __call__(self, url, headers, timeout):
        self.calls.append((url, dict(headers)))
        path = url.removeprefix(BASE)
        if self.failing(path) or path not in PATHS:
            raise OSError(f"{path} unavailable")
        return json.dumps(self.load(PATHS[path])).encode()


def test_load_media_catalog_reads_every_surface_without_a_key_then_each_speech_models_voices(load):
    transport = FakeTransport(load)
    catalog = load_media_catalog(transport=transport, user_agent="app/1")
    assert catalog.source == "network"
    assert catalog.issues == []
    assert sorted(url.removeprefix(BASE) for url, _ in transport.calls) == sorted(PATHS)
    for _, headers in transport.calls:
        assert "Authorization" not in headers
        assert headers["User-Agent"].startswith("app/1 vultr-model-catalog/")
    assert [model.to_dict() for model in catalog.models] == load("media.normalized.json")


def test_a_source_that_fails_is_an_issue_and_the_rest_answer(load):
    catalog = load_media_catalog(transport=FakeTransport(load, lambda path: path == "/videos/models"))
    assert catalog.source == "network"
    assert [issue.source for issue in catalog.issues] == ["video"]
    h3 = next(model for model in catalog.models if model.id == "minimax-h3")
    assert h3.video is None and h3.image


def test_a_complete_load_is_cached_and_a_partial_one_is_served_from_it_stale(load, tmp_path):
    path = tmp_path / "nested" / "media.json"
    assert load_media_catalog(transport=FakeTransport(load), cache_path=path, now=lambda: 1.0).source == "network"

    partial = load_media_catalog(transport=FakeTransport(load, lambda p: p == "/music/models"), cache_path=path, now=lambda: 2.0)
    assert partial.source == "stale-cache"
    assert partial.fetched_at == 1000
    assert [issue.source for issue in partial.issues] == ["music"]
    assert next(model for model in partial.models if model.id == "minimax-music3").music

    fresh = FakeTransport(load)
    cached = load_media_catalog(transport=fresh, cache_path=path, max_age=5, now=lambda: 3.0)
    assert cached.source == "cache"
    assert fresh.calls == []

    # The partial load did not replace the cache, which the TypeScript library reads too
    written = json.loads(path.read_text(encoding="utf-8"))
    assert written["fetched_at"] == 1000
    assert sorted(written) == ["base_url", "fetched_at", "payloads"]
    assert sorted(written["payloads"]) == ["image", "music", "public", "video", "voices"]


def test_every_source_down_and_no_cache_is_a_catalog_error(load):
    with pytest.raises(CatalogError):
        load_media_catalog(transport=FakeTransport(load, lambda path: True))
